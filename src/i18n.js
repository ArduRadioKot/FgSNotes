    let lang = 'ru';
    function t(key, vars) {
        const text = lang === 'en' ? (EN[key] != null ? EN[key] : key) : (RU[key] != null ? RU[key] : key);
        if (!vars) return text;
        return Object.keys(vars).reduce((out, name) => out.split('{' + name + '}').join(String(vars[name])), text);
    }
    const originals = new WeakMap();
    const skipSelector = '.preview-content, .cm-editor, .cm-content, .ai-bubble, .ai-think-body, .tab, .plugin-view, #about-update-notes, [data-i18n-skip]';
    function known(key) { return !!(key && (EN[key] != null || RU[key] != null)); }
    function norm(text) { return String(text).replace(/\s+/g, ' ').trim(); }
    function remember(el, field, value, force) {
        let bag = originals.get(el);
        if (!bag) originals.set(el, bag = {});
        if (force || bag[field] == null) bag[field] = value;
        return bag[field];
    }
    function translateLeaf(el) {
        if (!el || el.nodeType !== 1 || el.childElementCount) return;
        if (el.tagName === 'TITLE') return;
        if (el.closest && el.closest(skipSelector)) return;
        if (el.matches && el.matches('script, style, textarea, input, pre, code')) return;
        const bag = originals.get(el);
        const fresh = known(norm(el.textContent)) ? norm(el.textContent) : '';
        const key = fresh || (bag && bag.text != null ? bag.text : '');
        if (!known(key)) return;
        remember(el, 'text', key, !!fresh);
        const next = t(key);
        if (el.textContent !== next) el.textContent = next;
    }
    function translateAttr(el, attr) {
        if (!el.hasAttribute(attr)) return;
        if (attr !== 'placeholder' && el.closest && el.closest(skipSelector)) return;
        const current = el.getAttribute(attr);
        if (!current) return;
        const bag = originals.get(el);
        const stored = bag && bag[attr];
        const fresh = known(current) ? current : known(norm(current)) ? norm(current) : '';
        const key = fresh || (stored && known(stored) ? stored : '');
        if (!key) return;
        remember(el, attr, key, !!fresh);
        const next = t(key);
        if (el.getAttribute(attr) !== next) el.setAttribute(attr, next);
    }
    function apply(scope) {
        if (typeof document === 'undefined') return;
        const rootNode = scope && scope.querySelectorAll ? scope : document;
        const list = [];
        rootNode.querySelectorAll('*').forEach(el => list.push(el));
        list.forEach(el => {
            if (!el || el.nodeType !== 1) return;
            translateLeaf(el);
            ['title', 'aria-label', 'placeholder', 'alt', 'label'].forEach(attr => translateAttr(el, attr));
            if (el.hasAttribute && el.hasAttribute('data-i18n')) {
                remember(el, 'text', el.getAttribute('data-i18n'));
                el.textContent = t(el.getAttribute('data-i18n'));
            }
            if (el.hasAttribute && el.hasAttribute('data-i18n-title')) el.title = t(el.getAttribute('data-i18n-title'));
            if (el.hasAttribute && el.hasAttribute('data-i18n-aria')) el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
            if (el.hasAttribute && el.hasAttribute('data-i18n-placeholder')) el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
        });
        if (!scope || scope === document) document.documentElement.lang = lang;
    }
    function detect() {
        if (typeof window !== 'undefined' && window.electron && window.electron.bootConfig) {
            const boot = window.electron.bootConfig.language;
            if (boot === 'ru' || boot === 'en') return boot;
        }
        try {
            const saved = localStorage.getItem('fgsnotes.language');
            if (saved === 'ru' || saved === 'en') return saved;
        } catch { /* storage unavailable */ }
        const locale = (typeof navigator !== 'undefined' && navigator.language) || '';
        return /^ru/i.test(locale) ? 'ru' : 'en';
    }
    function setLanguage(code) {
        lang = code === 'en' ? 'en' : 'ru';
        try { localStorage.setItem('fgsnotes.language', lang); } catch { /* storage unavailable */ }
        if (typeof document !== 'undefined') {
            apply(document);
            window.dispatchEvent(new CustomEvent('fgs-language', { detail: lang }));
        }
        if (typeof window !== 'undefined' && window.electron && window.electron.setLanguage) window.electron.setLanguage(lang);
        return lang;
    }
    function init() {
        lang = detect();
        if (typeof document === 'undefined') return;
        const start = () => apply(document);
        if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
        else start();
        if (typeof window !== 'undefined' && window.electron && window.electron.setLanguage) window.electron.setLanguage(lang);
    }
    if (typeof document !== 'undefined') init();
    const api = {
        t, apply, setLanguage, init,
        get language() { return lang; },
        get EN() { return EN; },
        get RU() { return RU; }
    };
    if (typeof globalThis !== 'undefined') globalThis.t = t;
    return api;
