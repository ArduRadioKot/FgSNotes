let sharedEnglish = null;
function fromApp(key) {
    if (!sharedEnglish) {
        const held = globalThis.t;
        sharedEnglish = require('../src/i18n').EN;
        if (held) globalThis.t = held;
        else delete globalThis.t;
    }
    return sharedEnglish[key];
}

function createI18n(initial) {
    let lang = initial === 'en' ? 'en' : 'ru';
    const t = (key, vars) => {
        let text = lang === 'en' ? (EN[key] != null ? EN[key] : (fromApp(key) != null ? fromApp(key) : key)) : key;
        if (vars) for (const name of Object.keys(vars)) text = text.split(`{${name}}`).join(String(vars[name]));
        return text;
    };
    t.setLanguage = code => { lang = code === 'en' ? 'en' : 'ru'; };
    t.language = () => lang;
    return t;
}

function countWord(t, value) {
    const mod100 = value % 100, mod10 = value % 10;
    const form = mod100 > 10 && mod100 < 20 ? '{n} слов' : mod10 === 1 ? '{n} слово' : mod10 >= 2 && mod10 <= 4 ? '{n} слова' : '{n} слов';
    return t(form, { n: value });
}

module.exports = { createI18n, countWord };
